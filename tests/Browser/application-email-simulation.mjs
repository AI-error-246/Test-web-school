import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import puppeteer from '../../../../../.tools/diagram-renderer/node_modules/puppeteer/lib/puppeteer/puppeteer.js';

const appRoot = fileURLToPath(new URL('../../', import.meta.url));
const php = fileURLToPath(new URL('../../../../../.tools/php-8.4.26/php.exe', import.meta.url));
const output = fileURLToPath(new URL('../../../../06_Testing/application-email/', import.meta.url));
await mkdir(output, { recursive: true });
const result = { at: new Date().toISOString(), mode: 'SIMULATION_ONLY', checks: [], errors: [] };
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: false, defaultViewport: { width: 1280, height: 900 }, args: ['--no-first-run', '--window-size=1400,1000'] });
const page = await browser.newPage();
page.on('pageerror', e => result.errors.push(e.name));
const go = path => page.goto('http://127.0.0.1:3002' + path, { waitUntil: 'networkidle0' });
const submit = selector => Promise.all([page.waitForNavigation({ waitUntil: 'networkidle0' }), page.click(selector)]);
const login = async role => {
    await go('/login');
    await page.type('[name=email]', role + '@simulation.test');
    await page.type('[name=password]', 'Simulation-only-2026');
    await submit('form[action$="/login"] button[type=submit]');
};
try {
    await login('employer');
    await go('/applications/1');
    const select = await page.$('select[name=status]');
    assert.ok(select, 'Demo application needs a non-terminal status');
    const values = await page.$$eval('select[name=status] option', options => options.map(o => o.value));
    const nextStatus = values.includes('REVIEWING') ? 'REVIEWING' : 'REJECTED';
    await page.select('select[name=status]', nextStatus);
    const began = Date.now();
    await submit('form[action$="/employer/applications/1"] button');
    result.transitionElapsedMs = Date.now() - began;
    await page.screenshot({ path: output + 'employer-status.png', fullPage: true });
    result.checks.push('Employer commits status through normal form');
    await submit('form[action$="/logout"] button');
    await login('candidate');
    await go('/candidate/notifications');
    assert.ok((await page.$eval('main', e => e.innerText)).includes('Chờ xử lý'));
    result.checks.push('Candidate sees durable pending email after committed transition');
    const delivered = execFileSync(php, ['tests/Support/security_demo_router.php', 'deliver'], { cwd: appRoot, env: { ...process.env, INTERNBRIDGE_SECURITY_DEMO: '1' }, encoding: 'utf8' });
    assert.match(delivered, /PREVIEWED: 1/);
    const repeated = execFileSync(php, ['tests/Support/security_demo_router.php', 'deliver'], { cwd: appRoot, env: { ...process.env, INTERNBRIDGE_SECURITY_DEMO: '1' }, encoding: 'utf8' });
    assert.match(repeated, /Processed 0 message/);
    result.checks.push('Outbox processes once as PREVIEWED; repeat command creates no duplicate');
    await go('/candidate/notifications');
    await page.screenshot({ path: output + 'candidate-notifications.png', fullPage: true });
    const previewPath = await page.$eval('a[href$="/email"]', e => new URL(e.href).pathname);
    const response = await go(previewPath);
    assert.equal(response.status(), 200);
    assert.ok((await page.$eval('body', e => e.innerText)).includes('Hồ sơ của bạn có cập nhật mới'));
    assert.ok((await page.$eval('body', e => e.innerText)).includes('MÔ PHỎNG'));
    assert.ok(response.headers()['content-security-policy'].includes("default-src 'none'"));
    await page.screenshot({ path: output + 'email-desktop.png', fullPage: true });
    await page.setViewport({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: output + 'email-mobile.png', fullPage: true });
    result.checks.push('Private Vietnamese email preview, safe link/CSP and mobile without overflow');
    await page.setViewport({ width: 1280, height: 900 });
    await go('/candidate/notifications');
    await submit('form[action$="/logout"] button');
    await go(previewPath);
    assert.equal(new URL(page.url()).pathname, '/login');
    await login('employer');
    assert.equal((await go(previewPath)).status(), 403);
    result.checks.push('Guest and employer cannot open candidate email preview');
    await go('/employer');
    await submit('form[action$="/logout"] button');
    await login('candidate');
    await go('/candidate/notifications');
    assert.deepEqual(result.errors, []);
    result.status = 'PASS';
} catch (error) {
    result.status = 'FAIL';
    result.error = error.message;
    process.exitCode = 1;
} finally {
    await writeFile(output + 'browser.json', JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result));
    await browser.close();
}
